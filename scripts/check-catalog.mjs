import { chromium } from "playwright";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const base = process.env.PREVIEW_URL || "http://127.0.0.1:3000";
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
  const page = await context.newPage();
  const external = []; page.on("request", r => { if (!r.url().startsWith(base) && !r.url().startsWith("data:") && !r.url().startsWith("blob:")) external.push(r.url()); });
  await page.goto(base, { waitUntil: "networkidle" }); assert.equal(await page.locator(".product-card").count(), 6);
  await page.getByRole("button", { name: /^לשולחן ולשבת/ }).click(); assert.equal(await page.locator(".product-card").count(), 3);
  const trigger = page.getByRole("button", { name: "מבט מקרוב: אור בכחול" }); await trigger.click();
  const dialog = page.getByRole("dialog"); await dialog.waitFor();
  assert.equal(await dialog.getByRole("heading", { level: 2 }).textContent(), "אור בכחול");
  await dialog.locator(".dialog-close").focus(); await page.keyboard.press("Shift+Tab"); assert.equal(await page.evaluate(() => document.querySelector("dialog").contains(document.activeElement)), true);
  const axe = await new AxeBuilder({ page }).analyze(); assert.equal(axe.violations.length, 0, JSON.stringify(axe.violations));
  await dialog.getByRole("button", { name: "הוספה לרשימת הבחירות", exact: true }).click();
  await dialog.getByRole("button", { name: /לרשימת הבחירות/ }).click();
  const [download] = await Promise.all([page.waitForEvent("download"), dialog.getByRole("button", { name: "שמירת רשימת הבחירות" }).click()]);
  assert.equal(download.suggestedFilename(), "rimon-selection.txt");
  const text = await readFile(await download.path(), "utf8"); assert.ok(text.includes("אור בכחול")); assert.ok(text.includes("אינם מוצעים למכירה"));
  await dialog.getByRole("button", { name: "הסרת אור בכחול מהסל" }).click(); assert.equal(await dialog.locator(".empty-cart").isVisible(), true);
  await page.keyboard.press("Escape"); assert.equal(await trigger.evaluate(node => node === document.activeElement), true);
  await page.getByRole("button", { name: /^אמנות לבית/ }).click(); assert.equal(await page.locator(".product-card").count(), 3);
  await page.getByRole("button", { name: "הוספה לרשימת הבחירות: ברכה בפתח", exact: true }).click();
  await page.getByRole("button", { name: /^הכול/ }).click(); assert.equal(await page.locator(".bag-count").textContent(), "1");
  await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole("button", { name: "מבט מקרוב: ברכה בפתח" }).click();
  assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth), false);
  await page.keyboard.press("Escape");
  assert.deepEqual(external, []);
  console.log("Catalog checks passed: six items, filtering, dialog keyboard focus, local download, selection persistence, mobile layout and no external requests.");
} finally { await browser.close(); }
