import { chromium } from "playwright";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";

await mkdir("reports", { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const base = process.env.PREVIEW_URL || "http://127.0.0.1:3000";
const checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const externalRequests = [];
  page.on("request", request => { if (!request.url().startsWith(base) && !request.url().startsWith("data:")) externalRequests.push(request.url()); });
  await page.goto(base, { waitUntil: "networkidle" });
  assert.equal(await page.locator(".product-card").count(), 6);
  await page.getByRole("button", { name: /^מפות ישראל/ }).click();
  assert.equal(await page.locator(".product-card").count(), 2);
  await page.getByRole("button", { name: "מבט מקרוב: מפת ישראל בזהב" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.equal(await dialog.getByRole("heading", { level: 2 }).textContent(), "מפת ישראל בזהב");
  const close = dialog.getByRole("button", { name: "סגירת חלון הקטלוג" });
  await close.focus();
  await page.keyboard.press("Shift+Tab");
  assert.equal(await page.evaluate(() => document.querySelector("dialog").contains(document.activeElement)), true);
  const a11y = await new AxeBuilder({ page }).analyze();
  assert.equal(a11y.violations.length, 0, JSON.stringify(a11y.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, reason: n.failureSummary })) }))));
  await dialog.getByRole("button", { name: "הוספה לסל הפנייה" }).click();
  await dialog.getByRole("button", { name: /לסל הפנייה/ }).click();
  assert.equal(await dialog.getByRole("heading", { level: 2 }).textContent(), "הבחירות שלכם.");
  assert.equal(await page.locator(":focus").getAttribute("class"), "dialog-close");
  const inquiry = dialog.getByRole("link", { name: "בירור הבחירות ב־WhatsApp" });
  const url = new URL(await inquiry.getAttribute("href"));
  assert.equal(url.pathname, "/972547007608");
  assert.ok(url.searchParams.get("text").includes("מפת ישראל בזהב"));
  assert.ok(url.searchParams.get("text").includes("פנייה לבירור בלבד"));
  await page.screenshot({ path: "reports/inquiry-cart.png", animations: "disabled" });
  await dialog.getByRole("button", { name: "הסרת מפת ישראל בזהב מהסל" }).click();
  assert.equal(await dialog.getByText("עוד לא בחרתם עבודה שאהבתם.").isVisible(), true);
  await page.keyboard.press("Escape");
  assert.equal(await dialog.isVisible(), false);
  assert.equal(await page.locator(":focus").getAttribute("aria-label"), "מבט מקרוב: מפת ישראל בזהב");
  checks.push("Filtering, quick view, native dialog focus containment, focus restoration, add/remove and WhatsApp inquiry passed.");
  await page.getByRole("button", { name: /^הכול/ }).click();
  assert.equal(await page.locator(".product-card").count(), 6);
  await page.getByRole("button", { name: "הוספה לסל הפנייה: חי", exact: true }).click();
  await page.getByRole("button", { name: /^מפות ישראל/ }).click();
  assert.equal(await page.locator(".bag-count").textContent(), "1");
  await page.getByRole("button", { name: /סל פנייה/ }).click();
  assert.equal(await dialog.getByRole("heading", { name: "חי", exact: true }).isVisible(), true);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "השהיית תנועה", exact: true }).click();
  assert.equal(await page.locator("html").getAttribute("data-motion"), "paused");
  assert.equal(await page.locator(".seal-type").evaluate(e => getComputedStyle(e).animationPlayState), "paused");
  await page.getByRole("button", { name: "הפעלת תנועה", exact: true }).click();
  assert.equal(await page.locator("html").getAttribute("data-motion"), "running");
  await page.emulateMedia({ reducedMotion: "reduce" });
  assert.equal(await page.locator(".seal-type").evaluate(e => getComputedStyle(e).animationName), "none");
  checks.push("Selections survive category changes. Animation pause and OS reduced-motion preference are respected.");
  await page.goto(`${base}/photo-credits/`, { waitUntil: "networkidle" });
  assert.equal(await page.getByRole("heading", { level: 1 }).textContent(), "העבודות והסיפור שלהן.");
  assert.equal(externalRequests.length, 0, "Public pages must serve all assets locally");
  checks.push("Photography credits available. No external asset requests.");
  const mobile = await context.newPage();
  await mobile.setViewportSize({ width: 390, height: 844 });
  await mobile.goto(base, { waitUntil: "networkidle" });
  await mobile.getByRole("button", { name: "מבט מקרוב: חי" }).click();
  const mobileDialog = mobile.getByRole("dialog");
  await mobileDialog.waitFor();
  assert.equal(await mobileDialog.evaluate(d => d.scrollWidth > d.clientWidth), false);
  assert.equal(await mobileDialog.getByRole("button", { name: "הוספה לסל הפנייה" }).isVisible(), true);
  await mobile.keyboard.press("Escape");
  checks.push("Mobile quick view fits the screen and can be closed with Escape.");
  await writeFile("reports/catalog-checks.json", JSON.stringify(checks, null, 2));
  console.log(`Catalog: ${checks.length} groups of interaction checks passed.`);
} finally { await browser.close(); }
